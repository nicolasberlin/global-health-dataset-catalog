COLLECTION_JOBS_SCHEMA = """
CREATE TABLE collection_jobs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_url TEXT NOT NULL CHECK(source_url <> ''),
    kind TEXT NOT NULL DEFAULT 'source'
        CHECK(kind IN ('source', 'repository_candidate')),
    repository_candidate_id UUID,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK(status IN ('pending', 'running', 'done', 'error')),
    saved_count INTEGER NOT NULL DEFAULT 0 CHECK(saved_count >= 0),
    discovered_count INTEGER NOT NULL DEFAULT 0 CHECK(discovered_count >= 0),
    analyzed_count INTEGER NOT NULL DEFAULT 0 CHECK(analyzed_count >= 0),
    accepted_count INTEGER NOT NULL DEFAULT 0 CHECK(accepted_count >= 0),
    rejected_count INTEGER NOT NULL DEFAULT 0 CHECK(rejected_count >= 0),
    invalid_distribution_count INTEGER NOT NULL DEFAULT 0
        CHECK(invalid_distribution_count >= 0),
    discovery_methods JSONB NOT NULL DEFAULT '[]'::jsonb
        CHECK(jsonb_typeof(discovery_methods) = 'array'),
    message TEXT NOT NULL DEFAULT '',
    error TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ,
    validation_failures JSONB NOT NULL DEFAULT '[]'::jsonb
        CHECK(jsonb_typeof(validation_failures) = 'array'),
    classification_progress JSONB NOT NULL DEFAULT '{}'::jsonb,
    classification_root_id INTEGER REFERENCES collection_jobs(id),
    errors JSONB NOT NULL DEFAULT '[]'::jsonb CHECK(jsonb_typeof(errors) = 'array'),
    outcome TEXT CHECK(outcome IN ('results', 'empty', 'incomplete')),
    retry_cycle UUID NOT NULL DEFAULT gen_random_uuid(),
    retry_round INTEGER NOT NULL DEFAULT 0 CHECK(retry_round >= 0),
    retry_started_at TIMESTAMPTZ,
    next_retry_at TIMESTAMPTZ,
    collection_deadline_at TIMESTAMPTZ,
    collection_coverage JSONB NOT NULL DEFAULT '{}'::jsonb,
    collection_method_summary JSONB NOT NULL DEFAULT '[]'::jsonb,
    FOREIGN KEY(repository_candidate_id)
        REFERENCES repository_candidates(id) ON DELETE RESTRICT,
    CHECK(
        (kind = 'source' AND repository_candidate_id IS NULL)
        OR (kind = 'repository_candidate' AND repository_candidate_id IS NOT NULL)
    )
)
"""
