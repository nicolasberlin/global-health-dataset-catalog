# PostgreSQL must build vectors and queries with the same configuration;
# english handles grammar words and common lexical variants in the metadata.
COLLECTED_DATASETS_SEARCH_VECTOR_FUNCTION = f"""
CREATE OR REPLACE FUNCTION update_collected_datasets_search_vector()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.search_vector :=
        setweight(
            to_tsvector('{DATASET_SEARCH_TEXT_CONFIGURATION}', COALESCE(NEW.title, '')),
            'A'
        ) ||
        setweight(
            to_tsvector(
                '{DATASET_SEARCH_TEXT_CONFIGURATION}',
                COALESCE(NEW.description, '')
            ),
            'B'
        ) ||
        setweight(
            to_tsvector(
                '{DATASET_SEARCH_TEXT_CONFIGURATION}',
                concat_ws(' ', NEW.publisher, NEW.geography::text)
            ),
            'C'
        ) ||
        setweight(
            to_tsvector(
                '{DATASET_SEARCH_TEXT_CONFIGURATION}',
                concat_ws(
                    ' ',
                    NEW.hosting_platform,
                    NEW.uploader,
                    regexp_replace(
                        NEW.dataset_url,
                        '[^[:alnum:]]+',
                        ' ',
                        'g'
                    )
                )
            ),
            'D'
        );
    RETURN NEW;
END
$$
"""
COLLECTED_DATASETS_SEARCH_VECTOR_TRIGGER = """
CREATE TRIGGER collected_datasets_search_vector_update
BEFORE INSERT OR UPDATE OF
    title,
    description,
    publisher,
    hosting_platform,
    uploader,
    geography,
    dataset_url
ON collected_datasets
FOR EACH ROW
EXECUTE FUNCTION update_collected_datasets_search_vector()
"""
COLLECTED_DATASETS_SEARCH_VECTOR_INDEX = """
CREATE INDEX collected_datasets_search_vector_idx
ON collected_datasets
USING GIN(search_vector)
"""

SEARCH_SESSIONS_SCHEMA = """
CREATE TABLE search_sessions (
    id UUID PRIMARY KEY,
    owner_id TEXT NOT NULL CHECK(btrim(owner_id) <> '' AND char_length(owner_id) <= 200),
    query TEXT NOT NULL CHECK(btrim(query) <> ''),
    origin TEXT NOT NULL DEFAULT 'database'
        CHECK(origin IN ('database', 'online')),
    status TEXT NOT NULL DEFAULT 'running'
        CHECK(status IN ('queued', 'running', 'completed', 'partial', 'error')),
    error TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ,
    errors JSONB NOT NULL DEFAULT '[]'::jsonb CHECK(jsonb_typeof(errors) = 'array'),
    local_result_count INTEGER CHECK(local_result_count >= 0),
    discovery_complete BOOLEAN,
    execution_mode TEXT NOT NULL DEFAULT 'inline' CHECK(execution_mode IN ('inline', 'worker')),
    access_mode TEXT CHECK(access_mode IN ('local', 'public')),
    client_key TEXT,
    attempt_number INTEGER NOT NULL DEFAULT 1 CHECK(attempt_number >= 1),
    attempt_token UUID,
    online_quota_attempt INTEGER NOT NULL DEFAULT 0 CHECK(online_quota_attempt >= 0),
    warnings JSONB NOT NULL DEFAULT '[]'::jsonb CHECK(jsonb_typeof(warnings) = 'array'),
    retry_at TIMESTAMPTZ,
    CONSTRAINT search_sessions_lifecycle_check CHECK(
        (status IN ('queued', 'running') AND finished_at IS NULL)
        OR (status NOT IN ('queued', 'running') AND finished_at IS NOT NULL)
    ),
    CONSTRAINT search_sessions_check1 CHECK(
        (status = 'error' AND btrim(error) <> '')
        OR (status <> 'error' AND error = '')
    )
)
"""

