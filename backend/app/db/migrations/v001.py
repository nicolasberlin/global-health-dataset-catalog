REPOSITORY_CANDIDATES_SCHEMA = """
CREATE TABLE repository_candidates (
    id UUID PRIMARY KEY,
    search_session_id UUID NOT NULL,
    title TEXT NOT NULL CHECK(btrim(title) <> ''),
    description TEXT NOT NULL DEFAULT '',
    url TEXT NOT NULL CHECK(btrim(url) <> ''),
    source TEXT NOT NULL CHECK(btrim(source) <> ''),
    publisher TEXT NOT NULL DEFAULT '',
    publication_date TEXT NOT NULL DEFAULT '',
    doi TEXT NOT NULL DEFAULT '',
    keywords JSONB NOT NULL DEFAULT '[]'::jsonb
        CHECK(jsonb_typeof(keywords) = 'array'),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
        CHECK(jsonb_typeof(metadata) = 'object'),
    classification_status TEXT NOT NULL DEFAULT 'pending'
        CHECK(classification_status IN (
            'pending', 'queued', 'classifying', 'accepted', 'rejected', 'error'
        )),
    classification JSONB
        CHECK(classification IS NULL OR jsonb_typeof(classification) = 'object'),
    error TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    classification_progress JSONB NOT NULL DEFAULT '{}'::jsonb,
    errors JSONB NOT NULL DEFAULT '[]'::jsonb CHECK(jsonb_typeof(errors) = 'array'),
    retry_cycle UUID NOT NULL DEFAULT gen_random_uuid(),
    retry_round INTEGER NOT NULL DEFAULT 0 CHECK(retry_round >= 0),
    retry_started_at TIMESTAMPTZ,
    next_retry_at TIMESTAMPTZ,
    FOREIGN KEY(search_session_id) REFERENCES search_sessions(id) ON DELETE CASCADE,
    UNIQUE(search_session_id, source, url),
    CHECK(
        (classification_status IN ('pending', 'queued', 'classifying')
            AND classification IS NULL AND error = '')
        OR (classification_status IN ('accepted', 'rejected')
            AND classification IS NOT NULL AND error = '')
        OR (classification_status = 'error'
            AND classification IS NULL AND btrim(error) <> '')
    )
)
"""
